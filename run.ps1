# Rebuild everything: fetch fresh data, score it, and write the site's data files.
# Usage:  powershell -ExecutionPolicy Bypass -File run.ps1            (fetch + build)
#         powershell -ExecutionPolicy Bypass -File run.ps1 -SkipFetch (rebuild from existing data/raw)
param([switch]$SkipFetch)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$duckdb = Join-Path $PSScriptRoot 'tools\duckdb\duckdb.exe'
if (-not (Test-Path $duckdb)) { throw "DuckDB not found at $duckdb. See README 'Setup'." }

if (-not $SkipFetch) { & (Join-Path $PSScriptRoot 'pipeline\fetch.ps1') }

New-Item -ItemType Directory -Force 'site\data' | Out-Null
& $duckdb -no-agent 'data\priority.duckdb' -f 'pipeline\build.sql'
if ($LASTEXITCODE -ne 0) { throw "build.sql failed" }

# Wrap the JSON in one JS file so site/index.html works when opened directly (no web server).
# Every input is read as UTF-8 (Windows PowerShell would otherwise read it as ANSI and garble dashes and accents).
# The data is handed to the browser as one JSON string for JSON.parse, which phones read several times faster than
# the same data written as a JavaScript object.
$utf8 = New-Object Text.UTF8Encoding $false
function Read-Utf8([string]$p) { [IO.File]::ReadAllText((Join-Path $PSScriptRoot $p), [Text.Encoding]::UTF8).Trim() }
$fetched = if (Test-Path 'data\raw\fetched_at.txt') { (Read-Utf8 'data\raw\fetched_at.txt') } else { '' }
$projEdited = if (Test-Path 'data\raw\proj_edited.json') { (Read-Utf8 'data\raw\proj_edited.json') } else { '{}' }
$credits = if (Test-Path 'data\raw\basemap_credits.json') { (Read-Utf8 'data\raw\basemap_credits.json') } else { '{}' }
$sources = if (Test-Path 'data\raw\sources.json') { (Read-Utf8 'data\raw\sources.json') } else { '[]' }   # the datasets read, from the fetch step
# Two files: data.js has what the first screen needs (the map, the lists, the place panel). data-late.js has search,
# "Is it getting fixed?" and the budget; the page asks for it once data.js is in, so the first screen loads sooner.
$json = '{"fetchedAt":' + (ConvertTo-Json $fetched) +
        ',"credits":'    + $credits +
        ',"sources":'    + $sources +
        ',"meta":'       + (Read-Utf8 'site\data\meta.json') +
        ',"priorities":' + (Read-Utf8 'site\data\priorities.json') +
        ',"boundary":'   + (Read-Utf8 'site\data\boundary.json') +
        ',"labels":'     + (Read-Utf8 'site\data\labels.json') +
        ',"traffic":'    + (Read-Utf8 'site\data\traffic.json') +
        ',"sidewalks":'  + (Read-Utf8 'site\data\sidewalks.json') +
        ',"projects":'   + (Read-Utf8 'site\data\projects.json') +
        ',"projEdited":' + $projEdited +
        ',"context":'    + (Read-Utf8 'site\data\context.json') + '}'
$lateJson = '{"search":'   + (Read-Utf8 'site\data\search.json') +
            ',"progress":' + (Read-Utf8 'site\data\progress.json') +
            ',"budget":'   + (Read-Utf8 'site\data\sdot_budget.json') +
            ',"addrStreets":' + (Read-Utf8 'site\data\addr_streets.json') +
            ',"walkZones":' + (Read-Utf8 'site\data\walk_zones.json') + '}'
# Inside a single-quoted JS string: escape backslashes and quotes; line breaks between JSON values become spaces.
function To-JsLit([string]$s) { $s.Replace('\', '\\').Replace("'", "\'").Replace("`r", ' ').Replace("`n", ' ') }
$lit = To-JsLit $json
$lateLit = To-JsLit $lateJson

# The data fingerprint (for cache-busting and to tell area files from different builds apart), from the inputs.
function Get-Tag([string[]]$Paths) {
  $all = -join ($Paths | ForEach-Object { (Get-FileHash $_ -Algorithm SHA256).Hash })
  $sha = [Security.Cryptography.SHA256]::Create()
  (-join ($sha.ComputeHash([Text.Encoding]::ASCII.GetBytes($all)) | Select-Object -First 5 | ForEach-Object { $_.ToString('x2') }))
}
$dataJs = Join-Path $PSScriptRoot 'site\data\data.js'
$tmpJson = Join-Path $PSScriptRoot 'data\site_data.json'
$tmpLate = Join-Path $PSScriptRoot 'data\site_late.json'
[IO.File]::WriteAllText($tmpJson, $json, $utf8)
[IO.File]::WriteAllText($tmpLate, $lateJson, $utf8)
$dataTag = Get-Tag @($tmpJson, $tmpLate, (Join-Path $PSScriptRoot 'data\more.ndjson'), (Join-Path $PSScriptRoot 'data\addr.ndjson'))
Remove-Item $tmpJson, $tmpLate
$js = "// Generated by run.ps1. Do not edit.`n" +
      "window.SITE_DATA = (function (d) {`n" +
      "  ['boundary:boundary', 'labels:labels', 'traffic:traffic', 'sidewalks:sidewalks', 'projects:projects', 'context:ctx']`n" +
      "    .forEach(function (kv) { var p = kv.split(':'); d[p[0]] = d[p[0]] && d[p[0]][p[1]]; });`n" +
      "  d.version = '$dataTag';`n" +
      "  return d;`n" +
      "})(JSON.parse('" + $lit + "'));`n"
[IO.File]::WriteAllText($dataJs, $js, $utf8)
# The page loads this one itself (with the same fingerprint) and picks it up through window.siteLateReady.
$late = "// Generated by run.ps1. Do not edit.`n" +
        "window.SITE_LATE = (function (d) {`n" +
        "  d.search = d.search && d.search.idx; d.progress = d.progress && d.progress.progress;`n" +
        "  d.addrStreets = d.addrStreets && d.addrStreets.streets; d.walkZones = d.walkZones && d.walkZones.wz.zones; d.version = '$dataTag';`n" +
        "  return d;`n" +
        "})(JSON.parse('" + $lateLit + "'));`n" +
        "if (window.siteLateReady) window.siteLateReady(window.SITE_LATE);`n"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'site\data\data-late.js'), $late, $utf8)

# This week's full ranked list as a spreadsheet (site/data/ranks.csv), with the data date and each place's link. The
# weekly job keeps a copy of every week's list as a GitHub release (see .github/workflows/weekly.yml), so a rank quoted
# on a given day can be checked later. The link key is the same one the page makes (keyOf in app.js).
Add-Type -TypeDefinition @'
public static class SfKey {
  static string B36(uint v) { const string d = "0123456789abcdefghijklmnopqrstuvwxyz"; string s = ""; do { s = d[(int)(v % 36)] + s; v /= 36; } while (v > 0); return s; }
  public static string Of(string n) {
    unchecked {
      uint a = 0x811c9dc5, b = 0x01000193u ^ 0x5bd1e995u;
      foreach (char c in n) { a = (a ^ c) * 16777619u; b = (b ^ c) * 2246822519u; }
      string bs = B36(b);
      return B36(a) + (bs.Length > 4 ? bs.Substring(0, 4) : bs);
    }
  }
}
'@
$asOf = if ($fetched) { $fetched.Substring(0, 10) } else { (Get-Date).ToString('yyyy-MM-dd') }
$pageUrl = 'https://streetsfirst.org/seattle/'
$ranks = Import-Csv (Join-Path $PSScriptRoot 'data\ranks_raw.csv') -Encoding UTF8
if ($ranks.Count -lt 1000) { throw "ranks_raw.csv has only $($ranks.Count) places" }
$q = { param($v) $s = [string]$v; if ($s -match '[",\r\n]') { '"' + $s.Replace('"', '""') + '"' } else { $s } }
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine((@('Data as of', 'Rank', 'Type', "Place (SDOT's name)", 'Council district', 'Also in council district', 'Neighborhood',
  'All crashes', 'Crashes that killed or seriously hurt someone', 'Crashes that killed someone', 'People killed', 'People seriously injured',
  'Crashes involving someone walking', 'Crashes involving someone on a bike', 'Run by WSDOT', 'Score (expected harm)',
  'Crashes from', 'Crashes to', 'Link') | ForEach-Object { & $q $_ }) -join ',')
foreach ($r in $ranks) {
  [void]$sb.AppendLine((@($asOf, $r.rank, $r.type, $r.location, $r.council_district, $r.council_district2, $r.area,
    $r.crashes, $r.ksi, $r.fatal, $r.killed, $r.seriously_injured, $r.ped_crashes, $r.bike_crashes, $r.state_route, $r.score,
    $r.crashes_from, $r.crashes_to, ($pageUrl + '#p=' + [SfKey]::Of($r.location))) | ForEach-Object { & $q $_ }) -join ',')
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'site\data\ranks.csv'), $sb.ToString(), (New-Object Text.UTF8Encoding $true))
Write-Host "Wrote site\data\ranks.csv: $($ranks.Count) places, data as of $asOf"

# The top 50 as a checking sheet (site/data/top50_check.csv; made in build.sql): how the site reads SDOT's layers at
# each place, with SDOT's intersection keys, and an empty column for corrections.
$top = Import-Csv (Join-Path $PSScriptRoot 'data\top50_raw.csv') -Encoding UTF8
if ($top.Count -ne 50) { throw "top50_raw.csv has $($top.Count) places, not 50" }
$from = $top[0].crashes_from.Substring(0, 7); $to = $top[0].crashes_to.Substring(0, 7)
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine((@("Rank (as of $asOf)", 'Type', 'Place (as the site names it)',
  "SDOT intersection(s): INTKEY, SDOT's LOCATION, crashes there", 'Council district(s)',
  "Crashes $from to $to (duplicate reports removed)", 'Crashes that killed or seriously hurt someone',
  'No turn on red (SDOT NTOR layer)', 'Head-start walk signal (SDOT LPI layer)',
  'Protected left turn (SDOT signal layer, LTPROTECTEDYN: one Y/N per signal)', 'Other work at this place (SDOT layers)',
  "Work at the corners at this block's ends since $from", 'Run by', 'Link',
  'Optional: anything wrong? (a one-line email is plenty)') | ForEach-Object { & $q $_ }) -join ',')
foreach ($r in $top) {
  [void]$sb.AppendLine((@($r.rank, $r.type, $r.location, $r.intkeys, $r.districts, $r.crashes, $r.ksi, $r.ntor, $r.lpi,
    $r.left_turn, $r.other_work, $r.end_work, $r.run_by, ($pageUrl + '#p=' + [SfKey]::Of($r.location)), '') |
    ForEach-Object { & $q $_ }) -join ',')
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'site\data\top50_check.csv'), $sb.ToString(), (New-Object Text.UTF8Encoding $true))
Write-Host "Wrote site\data\top50_check.csv"

# "Increases to look into" as a spreadsheet (site/data/increases.csv; made in history.sql): the rows the page lists, with
# SDOT's location names and intersection keys, the data date and each place's link. An empty list is a valid week.
$inc = @(Import-Csv (Join-Path $PSScriptRoot 'data\increases_raw.csv') -Encoding UTF8)
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine((@('Data as of', 'Fix', 'Fix went in', 'Crashes it targets', "Place (SDOT's name)", "SDOT's location names in the crash reports",
  'SDOT intersection key (INTKEY)', 'Council district', 'Rank now', 'Targeted crashes before', 'Targeted crashes after',
  'Years counted on each side', 'Targeted crashes in the equal period before that', 'Link') | ForEach-Object { & $q $_ }) -join ',')
foreach ($r in $inc) {
  [void]$sb.AppendLine((@($asOf, $r.fix, $r.fix_date, $r.targets, $r.location, $r.sdot_names, $r.intkey, $r.district, $r.rank,
    $r.before, $r.after, $r.years_each_side, $r.earlier, ($pageUrl + '#p=' + [SfKey]::Of($r.location))) | ForEach-Object { & $q $_ }) -join ',')
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'site\data\increases.csv'), $sb.ToString(), (New-Object Text.UTF8Encoding $true))
Write-Host "Wrote site\data\increases.csv: $($inc.Count) places"
# Plain street names (addresses.sql): how many places the page names without SDOT's roadway code, and how many keep
# SDOT's spelling (no matching King County street, or the plain name would match another place's).
$pn = (Get-Content (Join-Path $PSScriptRoot 'site\data\meta.json') -Raw -Encoding UTF8 | ConvertFrom-Json).plain_names
if ($pn) { Write-Host "Street names: $($pn.places_plain) places shown with the plain name, $($pn.places_kept) kept in SDOT's spelling" }

# Full details for every place (crash list, requests; and the place's fields for places outside the ranked lists):
# one small script per map area, loaded only when someone opens a place there, so the main data file stays small.
# Each line of data\more.ndjson is one area. Each file carries the data fingerprint, so the page can tell when an area
# file comes from a newer build than the page it's loaded into.
$moreDir = Join-Path $PSScriptRoot 'site\data\more'
if (Test-Path $moreDir) { Remove-Item -Recurse -Force $moreDir }
New-Item -ItemType Directory -Force $moreDir | Out-Null
$n = 0
foreach ($line in [IO.File]::ReadLines((Join-Path $PSScriptRoot 'data\more.ndjson'), [Text.Encoding]::UTF8)) {
  if ($line -notmatch '^\{"cell":"([0-9_]+)"') { throw "Unexpected line in more.ndjson" }
  [IO.File]::WriteAllText((Join-Path $moreDir ($Matches[1] + '.js')), "SITE_MORE($line, '$dataTag');`n", $utf8)
  $n++
}
Write-Host "Wrote $n area files to site\data\more"

# House numbers for address suggestions: one small file per group of streets (data\addr.ndjson, from addresses.sql),
# loaded only when someone types an address on one of those streets.
$addrDir = Join-Path $PSScriptRoot 'site\data\addr'
if (Test-Path $addrDir) { Remove-Item -Recurse -Force $addrDir }
New-Item -ItemType Directory -Force $addrDir | Out-Null
$n = 0
foreach ($line in [IO.File]::ReadLines((Join-Path $PSScriptRoot 'data\addr.ndjson'), [Text.Encoding]::UTF8)) {
  if ($line -notmatch '^\{"s":(\d+),') { throw "Unexpected line in addr.ndjson" }
  [IO.File]::WriteAllText((Join-Path $addrDir ($Matches[1] + '.js')), "SITE_ADDR($line, '$dataTag');`n", $utf8)
  $n++
}
Write-Host "Wrote $n address files to site\data\addr"

# The picture shown when a link is shared (site\share.png, 1200 x 630): drawn from this week's data by
# pipeline\share_image.js and photographed with a headless Edge or Chrome (the same browser check.ps1 uses).
$shareHtml = Join-Path $PSScriptRoot 'data\share.html'
& node (Join-Path $PSScriptRoot 'pipeline\share_image.js') (Join-Path $PSScriptRoot 'site') (Join-Path $PSScriptRoot 'data\raw\fetched_at.txt') $shareHtml
if ($LASTEXITCODE -ne 0) { throw 'Share picture: drawing it failed' }
$browser = @("${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe", "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe",
  "$env:ProgramFiles\Google\Chrome\Application\chrome.exe", "${env:ProgramFiles(x86)}\Google\Chrome\Application\chrome.exe") |
  Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1
$sharePng = Join-Path $PSScriptRoot 'site\share.png'
if ($browser) {
  $userDir = Join-Path ([IO.Path]::GetTempPath()) ('ipm-share-' + [guid]::NewGuid())
  $ErrorActionPreference = 'Continue'   # the browser logs harmless noise to stderr
  & $browser --headless=new --disable-gpu --no-first-run --hide-scrollbars --user-data-dir="$userDir" --window-size=1200,630 `
    --screenshot="$sharePng" ([Uri]$shareHtml).AbsoluteUri 2>$null | Out-Null
  $ErrorActionPreference = 'Stop'
  Remove-Item $userDir -Recurse -Force -ErrorAction SilentlyContinue
}
if (-not (Test-Path $sharePng)) { Write-Warning 'Share picture: no browser to photograph it, so shared links show no picture this week' }
else { Write-Host "Share picture: site\share.png ($([int]((Get-Item $sharePng).Length / 1KB)) KB)" }

# Publishable copy: dist/ is site/ plus versioned addresses. site/ stays the clean source (open site/index.html locally).
# Cache-busting: each file's address in index.html carries a short fingerprint of its contents (data.js?v=3f9a...).
# A changed file gets a new address, so a browser never mixes in an old copy of it. (GitHub Pages ignores the ?v= part
# and lets browsers keep files about 10 minutes, then checks for a newer one; unchanged files answer that check cheaply.)
# The area files use the data fingerprint too (app.js adds it when it loads one).
$appTag = Get-Tag @(Join-Path $PSScriptRoot 'site\app.js')
$cssTag = Get-Tag @(Join-Path $PSScriptRoot 'site\style.css')
# Each city is published in its own folder (streetsfirst.org/seattle/), so links keep working as cities are added.
# The top level (root/) sends visitors to the city; later it can become a page for choosing one.
$dist = Join-Path $PSScriptRoot 'dist'
if (Test-Path $dist) { Remove-Item -Recurse -Force $dist }
New-Item -ItemType Directory -Force $dist | Out-Null
Copy-Item (Join-Path $PSScriptRoot 'root\*') $dist
$city = Join-Path $dist 'seattle'
Copy-Item (Join-Path $PSScriptRoot 'site') $city -Recurse
# The site reads only data.js, data-late.js and the area files; the intermediate JSON stays out of the published copy. The fetch's row
# counts are published so the next weekly run can compare against them (see .github/workflows/weekly.yml).
Remove-Item (Join-Path $city 'data\*.json')
if (Test-Path 'data\raw\counts.json') { Copy-Item 'data\raw\counts.json' (Join-Path $city 'data\counts.json') }
# The map credit lines too, so next week's run can fall back to them if an Esri layer can't be reached.
if (Test-Path 'data\raw\basemap_credits.json') { Copy-Item 'data\raw\basemap_credits.json' (Join-Path $city 'data\basemap_credits.json') }
$idx = Join-Path $city 'index.html'
$html = [IO.File]::ReadAllText($idx)
$html = $html -replace 'src="data/data\.js(\?v=[0-9a-f]*)?"', "src=`"data/data.js?v=$dataTag`""
$html = $html -replace 'src="app\.js(\?v=[0-9a-f]*)?"', "src=`"app.js?v=$appTag`""
$html = $html -replace 'href="style\.css(\?v=[0-9a-f]*)?"', "href=`"style.css?v=$cssTag`""
[IO.File]::WriteAllText($idx, $html, $utf8)
Write-Host "File versions: data $dataTag, app $appTag, style $cssTag. Publishable copy in dist\ (Seattle in dist\seattle\)"
Write-Host "Done. Open site\index.html"
