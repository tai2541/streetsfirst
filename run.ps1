# Rebuild everything: fetch fresh data, score it, and write the site's data files.
# Usage:  powershell -ExecutionPolicy Bypass -File run.ps1            (fetch + build)
#         powershell -ExecutionPolicy Bypass -File run.ps1 -SkipFetch (rebuild from existing data/raw)
param([switch]$SkipFetch)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$duckdb = Join-Path $PSScriptRoot 'tools\duckdb\duckdb.exe'
if (-not (Test-Path $duckdb)) { throw "DuckDB not found at $duckdb. See README 'Setup'." }

if (-not $SkipFetch) { & (Join-Path $PSScriptRoot 'pipeline\fetch.ps1') }

New-Item -ItemType Directory -Force 'site\data' | Out-Null
& $duckdb -no-agent 'data\priority.duckdb' -f 'pipeline\build.sql'
if ($LASTEXITCODE -ne 0) { throw "build.sql failed" }

# Wrap the JSON in one JS file so site/index.html works when opened directly (no web server).
$fetched = if (Test-Path 'data\raw\fetched_at.txt') { (Get-Content 'data\raw\fetched_at.txt' -Raw).Trim() } else { '' }
$projEdited = if (Test-Path 'data\raw\proj_edited.json') { (Get-Content 'data\raw\proj_edited.json' -Raw).Trim() } else { '{}' }
$js = "// Generated by run.ps1. Do not edit.`n" +
      "window.SITE_DATA = {`n" +
      "  fetchedAt: '$fetched',`n" +
      "  meta: "       + (Get-Content 'site\data\meta.json' -Raw)        + ",`n" +
      "  priorities: " + (Get-Content 'site\data\priorities.json' -Raw)  + ",`n" +
      "  budget: "     + (Get-Content 'site\data\sdot_budget.json' -Raw) + ",`n" +
      "  search: "     + (Get-Content 'site\data\search.json' -Raw)      + ".idx,`n" +
      "  boundary: "   + (Get-Content 'site\data\boundary.json' -Raw)    + ".boundary,`n" +
      "  labels: "     + (Get-Content 'site\data\labels.json' -Raw)      + ".labels,`n" +
      "  traffic: "    + (Get-Content 'site\data\traffic.json' -Raw)     + ".traffic,`n" +
      "  sidewalks: "  + (Get-Content 'site\data\sidewalks.json' -Raw)   + ".sidewalks,`n" +
      "  projects: "   + (Get-Content 'site\data\projects.json' -Raw)    + ".projects,`n" +
      "  projEdited: " + $projEdited                                     + ",`n" +
      "  context: "    + (Get-Content 'site\data\context.json' -Raw)     + ".ctx,`n" +
      "  details: "    + (Get-Content 'site\data\details.json' -Raw)     + ".details`n};`n"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'site\data\data.js'), $js, (New-Object Text.UTF8Encoding $false))

# Full details for places outside the ranked lists: one small script per map area, loaded only when someone
# opens a place there (so the main data file stays small). Each line of data\more.ndjson is one area.
$moreDir = Join-Path $PSScriptRoot 'site\data\more'
if (Test-Path $moreDir) { Remove-Item -Recurse -Force $moreDir }
New-Item -ItemType Directory -Force $moreDir | Out-Null
$utf8 = New-Object Text.UTF8Encoding $false
$n = 0
foreach ($line in [IO.File]::ReadLines((Join-Path $PSScriptRoot 'data\more.ndjson'))) {
  if ($line -notmatch '^\{"cell":"([0-9_]+)"') { throw "Unexpected line in more.ndjson" }
  [IO.File]::WriteAllText((Join-Path $moreDir ($Matches[1] + '.js')), "SITE_MORE($line);`n", $utf8)
  $n++
}
Write-Host "Wrote $n area files to site\data\more"
Write-Host "Done. Open site\index.html"
