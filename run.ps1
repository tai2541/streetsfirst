# Rebuild everything: fetch fresh data, score it, and write the site's data files.
# Usage:  powershell -ExecutionPolicy Bypass -File run.ps1            (fetch + build)
#         powershell -ExecutionPolicy Bypass -File run.ps1 -SkipFetch (rebuild from existing data/raw)
param([switch]$SkipFetch)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$duckdb = Join-Path $PSScriptRoot 'tools\duckdb\duckdb.exe'
if (-not (Test-Path $duckdb)) { throw "DuckDB not found at $duckdb. See README 'Setup'." }

if (-not $SkipFetch) { & (Join-Path $PSScriptRoot 'pipeline\fetch.ps1') }

New-Item -ItemType Directory -Force 'site\data' | Out-Null
& $duckdb -no-agent 'data\priority.duckdb' -f 'pipeline\build.sql'
if ($LASTEXITCODE -ne 0) { throw "build.sql failed" }

# Wrap the JSON in one JS file so site/index.html works when opened directly (no web server).
# Every input is read as UTF-8 (Windows PowerShell would otherwise read it as ANSI and garble dashes and accents).
# The data is handed to the browser as one JSON string for JSON.parse, which phones read several times faster than
# the same data written as a JavaScript object.
$utf8 = New-Object Text.UTF8Encoding $false
function Read-Utf8([string]$p) { [IO.File]::ReadAllText((Join-Path $PSScriptRoot $p), [Text.Encoding]::UTF8).Trim() }
$fetched = if (Test-Path 'data\raw\fetched_at.txt') { (Read-Utf8 'data\raw\fetched_at.txt') } else { '' }
$projEdited = if (Test-Path 'data\raw\proj_edited.json') { (Read-Utf8 'data\raw\proj_edited.json') } else { '{}' }
$credits = if (Test-Path 'data\raw\basemap_credits.json') { (Read-Utf8 'data\raw\basemap_credits.json') } else { '{}' }
$json = '{"fetchedAt":' + (ConvertTo-Json $fetched) +
        ',"credits":'    + $credits +
        ',"meta":'       + (Read-Utf8 'site\data\meta.json') +
        ',"priorities":' + (Read-Utf8 'site\data\priorities.json') +
        ',"budget":'     + (Read-Utf8 'site\data\sdot_budget.json') +
        ',"search":'     + (Read-Utf8 'site\data\search.json') +
        ',"boundary":'   + (Read-Utf8 'site\data\boundary.json') +
        ',"labels":'     + (Read-Utf8 'site\data\labels.json') +
        ',"traffic":'    + (Read-Utf8 'site\data\traffic.json') +
        ',"sidewalks":'  + (Read-Utf8 'site\data\sidewalks.json') +
        ',"projects":'   + (Read-Utf8 'site\data\projects.json') +
        ',"projEdited":' + $projEdited +
        ',"context":'    + (Read-Utf8 'site\data\context.json') +
        ',"progress":'   + (Read-Utf8 'site\data\progress.json') + '}'
# Inside a single-quoted JS string: escape backslashes and quotes; line breaks between JSON values become spaces.
$lit = $json.Replace('\', '\\').Replace("'", "\'").Replace("`r", ' ').Replace("`n", ' ')

# The data fingerprint (for cache-busting and to tell area files from different builds apart), from the inputs.
function Get-Tag([string[]]$Paths) {
  $all = -join ($Paths | ForEach-Object { (Get-FileHash $_ -Algorithm SHA256).Hash })
  $sha = [Security.Cryptography.SHA256]::Create()
  (-join ($sha.ComputeHash([Text.Encoding]::ASCII.GetBytes($all)) | Select-Object -First 5 | ForEach-Object { $_.ToString('x2') }))
}
$dataJs = Join-Path $PSScriptRoot 'site\data\data.js'
$tmpJson = Join-Path $PSScriptRoot 'data\site_data.json'
[IO.File]::WriteAllText($tmpJson, $json, $utf8)
$dataTag = Get-Tag @($tmpJson, (Join-Path $PSScriptRoot 'data\more.ndjson'))
Remove-Item $tmpJson
$js = "// Generated by run.ps1. Do not edit.`n" +
      "window.SITE_DATA = (function (d) {`n" +
      "  ['search:idx', 'boundary:boundary', 'labels:labels', 'traffic:traffic', 'sidewalks:sidewalks', 'projects:projects', 'context:ctx', 'progress:progress']`n" +
      "    .forEach(function (kv) { var p = kv.split(':'); d[p[0]] = d[p[0]] && d[p[0]][p[1]]; });`n" +
      "  d.version = '$dataTag';`n" +
      "  return d;`n" +
      "})(JSON.parse('" + $lit + "'));`n"
[IO.File]::WriteAllText($dataJs, $js, $utf8)

# Full details for every place (crash list, requests; and the place's fields for places outside the ranked lists):
# one small script per map area, loaded only when someone opens a place there, so the main data file stays small.
# Each line of data\more.ndjson is one area. Each file carries the data fingerprint, so the page can tell when an area
# file comes from a newer build than the page it's loaded into.
$moreDir = Join-Path $PSScriptRoot 'site\data\more'
if (Test-Path $moreDir) { Remove-Item -Recurse -Force $moreDir }
New-Item -ItemType Directory -Force $moreDir | Out-Null
$n = 0
foreach ($line in [IO.File]::ReadLines((Join-Path $PSScriptRoot 'data\more.ndjson'), [Text.Encoding]::UTF8)) {
  if ($line -notmatch '^\{"cell":"([0-9_]+)"') { throw "Unexpected line in more.ndjson" }
  [IO.File]::WriteAllText((Join-Path $moreDir ($Matches[1] + '.js')), "SITE_MORE($line, '$dataTag');`n", $utf8)
  $n++
}
Write-Host "Wrote $n area files to site\data\more"

# Publishable copy: dist/ is site/ plus versioned addresses. site/ stays the clean source (open site/index.html locally).
# Cache-busting: each file's address in index.html carries a short fingerprint of its contents (data.js?v=3f9a...).
# A changed file gets a new address, so a browser never mixes in an old copy of it. (GitHub Pages ignores the ?v= part
# and lets browsers keep files about 10 minutes, then checks for a newer one; unchanged files answer that check cheaply.)
# The area files use the data fingerprint too (app.js adds it when it loads one).
$appTag = Get-Tag @(Join-Path $PSScriptRoot 'site\app.js')
$cssTag = Get-Tag @(Join-Path $PSScriptRoot 'site\style.css')
# Each city is published in its own folder (streetsfirst.org/seattle/), so links keep working as cities are added.
# The top level (root/) sends visitors to the city; later it can become a page for choosing one.
$dist = Join-Path $PSScriptRoot 'dist'
if (Test-Path $dist) { Remove-Item -Recurse -Force $dist }
New-Item -ItemType Directory -Force $dist | Out-Null
Copy-Item (Join-Path $PSScriptRoot 'root\*') $dist
$city = Join-Path $dist 'seattle'
Copy-Item (Join-Path $PSScriptRoot 'site') $city -Recurse
# The site reads only data.js and the area files; the intermediate JSON stays out of the published copy. The fetch's row
# counts are published so the next weekly run can compare against them (see .github/workflows/weekly.yml).
Remove-Item (Join-Path $city 'data\*.json')
if (Test-Path 'data\raw\counts.json') { Copy-Item 'data\raw\counts.json' (Join-Path $city 'data\counts.json') }
$idx = Join-Path $city 'index.html'
$html = [IO.File]::ReadAllText($idx)
$html = $html -replace 'src="data/data\.js(\?v=[0-9a-f]*)?"', "src=`"data/data.js?v=$dataTag`""
$html = $html -replace 'src="app\.js(\?v=[0-9a-f]*)?"', "src=`"app.js?v=$appTag`""
$html = $html -replace 'href="style\.css(\?v=[0-9a-f]*)?"', "href=`"style.css?v=$cssTag`""
[IO.File]::WriteAllText($idx, $html, $utf8)
Write-Host "File versions: data $dataTag, app $appTag, style $cssTag. Publishable copy in dist\ (Seattle in dist\seattle\)"
Write-Host "Done. Open site\index.html"
